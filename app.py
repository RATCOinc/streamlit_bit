@st.cache_data
def get_end_sem_marks_from_xls(xls_file):
    end_sem_df = pd.read_excel(xls_file)
    
    target_string = "Roll No"
    # 1. Create a boolean mask where True means the string exists in that row
    row_mask = end_sem_df.astype(str).apply(
        lambda row: row.str.contains(target_string, case=False, na=False)
    ).any(axis=1)

    # 2. Get the index of the very first row where it appears
    start_idx = end_sem_df[row_mask].index[0]
    raw_headers = end_sem_df.iloc[start_idx].tolist()

    # --- DEDUPLICATE HEADERS ---
    unique_headers = []
    seen = {}
    for col in raw_headers:
        # Handle NaN (empty columns) safely
        col_str = str(col).strip() if pd.notna(col) else "Discard_Unnamed"
        
        # If the column name already exists, append _1, _2, etc.
        if col_str in seen:
            seen[col_str] += 1
            unique_headers.append(f"Discard_{col_str}_{seen[col_str]}")
        else:
            seen[col_str] = 0
            unique_headers.append(col_str)

    # 3. Slice the DataFrame from that row onward and reset index
    end_sem_df = end_sem_df.loc[start_idx+1:].reset_index(drop=True)
    
    # 4. Assign the uniquely generated headers
    end_sem_df.columns = unique_headers

    end_sem_df = end_sem_df.drop(columns=end_sem_df.filter(like='Discard_').columns)

    return end_sem_df






